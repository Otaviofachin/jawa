#[test]
fn registry_detection_reads_project_and_repo_npmrc() {
    let dir = tempfile::tempdir().unwrap();
    let repo = dir.path();
    let nested = repo.join("web");
    fs::create_dir_all(&nested).unwrap();
    assert_eq!(private_registry(&nested, repo), None);
    fs::write(
        repo.join(".npmrc"),
        "registry=https://registry.npmjs.org/\n",
    )
    .unwrap();
    assert_eq!(private_registry(&nested, repo), None);
    fs::write(
        nested.join(".npmrc"),
        "# nada\n@field:registry=https://npm.field.com/\n",
    )
    .unwrap();
    assert_eq!(
        private_registry(&nested, repo).as_deref(),
        Some("@field em npm.field.com")
    );
    fs::remove_file(nested.join(".npmrc")).unwrap();
    fs::write(
        repo.join(".npmrc"),
        "//npm.pkg.github.com/:_authToken=abc\n",
    )
    .unwrap();
    assert_eq!(
        private_registry(&nested, repo).as_deref(),
        Some("GitHub Packages")
    );
    fs::write(
        repo.join(".npmrc"),
        "@fieldcontrol:registry=https://npm.pkg.github.com\n//npm.pkg.github.com/:_authToken=${T}\n",
    )
    .unwrap();
    assert_eq!(
        private_registry(&nested, repo).as_deref(),
        Some("@fieldcontrol no GitHub Packages")
    );
}

