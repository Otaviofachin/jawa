struct NoTrash;

impl crate::clean::Discard for NoTrash {
    fn discard(&self, path: &Path) -> std::io::Result<()> {
        panic!("nada deveria ir para a Lixeira: {path:?}")
    }
}

#[test]
fn clean_blocks_when_a_process_runs_in_the_project() {
    use crate::clean::{CleanRequest, ExecContext, ItemOutcome, SkipReason, clean};
    let fx = git_fixture();
    let repo = project(&fx, "parado", 60);
    let ctx = fx.ctx_with(&SystemRunner, vec![fx.home.join("field")]);
    let findings = IdleNodeModules.scan(&ctx).unwrap().findings;
    assert_eq!(findings.len(), 1);
    let process_dir = fx.env.proc_root.join("4242");
    fs::create_dir_all(&process_dir).unwrap();
    symlink(&repo, process_dir.join("cwd")).unwrap();
    fs::write(process_dir.join("comm"), "node\n").unwrap();
    let mut ledger = crate::safety::ledger::Ledger::new(&fx.env, findings.clone());
    let request = CleanRequest {
        ids: findings.iter().map(|f| f.id.clone()).collect(),
        allow_irreversible: false,
    };
    let audit = crate::safety::audit::AuditLog::open(&fx.env).unwrap();
    let roots_for = |_: &crate::model::finding::Finding| IdleNodeModules.roots(&ctx);
    let watched_names_for =
        |finding: &crate::model::finding::Finding| IdleNodeModules.watched_processes_for(finding);
    let in_use_scope_for =
        |finding: &crate::model::finding::Finding| IdleNodeModules.in_use_scope(finding);
    let exec = ExecContext {
        env: &fx.env,
        runner: &SystemRunner,
        trash: &NoTrash,
        audit: &audit,
        roots_for: &roots_for,
        watched_names_for: &watched_names_for,
        in_use_scope_for: &in_use_scope_for,
    };
    let cancel = std::sync::atomic::AtomicBool::new(false);
    let report = clean(&mut ledger, &request, &exec, &|_| {}, &cancel).unwrap();
    assert!(matches!(
        report.items[0].1,
        ItemOutcome::Skipped(SkipReason::InUse(_))
    ));
    assert!(repo.join("node_modules").exists());
}

