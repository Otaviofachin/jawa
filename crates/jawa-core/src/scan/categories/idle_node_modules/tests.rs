use std::fs;
use std::os::unix::fs::symlink;
use std::time::{Duration, SystemTime};

use super::*;
use crate::scan::categories::test_support::{Fixture, fixture, write_bytes};
use crate::system::git::test_repo::{commit_all, git_exe, init_repo, set_age};
use crate::system::runner::SystemRunner;

const TWO_MIB: usize = 2 * 1024 * 1024;
const DAY: u64 = 86_400;

fn git_fixture() -> Fixture {
    let mut fx = fixture();
    fx.env.tools.git = Some(git_exe());
    // A hora extra absorve o tempo gasto criando os repositorios do teste.
    fx.env.now = SystemTime::now() + Duration::from_secs(3600);
    fx
}

fn project(fx: &Fixture, name: &str, days_ago: u64) -> PathBuf {
    let repo = fx.home.join("field").join(name);
    init_repo(&repo, days_ago);
    fs::write(repo.join(".gitignore"), "node_modules/\n").unwrap();
    write_bytes(&repo.join("node_modules/pkg/blob"), TWO_MIB);
    repo
}

fn scan(fx: &Fixture) -> Result<ScanOutput, ScanProblem> {
    let ctx = fx.ctx_with(&SystemRunner, vec![fx.home.join("field")]);
    IdleNodeModules.scan(&ctx)
}

fn note_of(output: &ScanOutput) -> &str {
    output.findings[0].note.as_deref().unwrap()
}

#[test]
fn offers_idle_and_skips_active() {
    let fx = git_fixture();
    project(&fx, "velho", 45);
    project(&fx, "novo", 2);
    let output = scan(&fx).unwrap();
    assert_eq!(output.findings.len(), 1);
    let finding = &output.findings[0];
    assert_eq!(finding.location, "~/field/velho/node_modules");
    assert_eq!(finding.label, "velho");
    assert_eq!(finding.risk, crate::model::finding::Risk::Review);
    assert_eq!(
        finding.reversibility,
        crate::model::finding::Reversibility::Regenerable
    );
    assert!(note_of(&output).starts_with("Última atividade há 45 dias. Para voltar: npm install."));
    assert_eq!(
        output.footnote.as_deref(),
        Some("1 projeto com atividade nos últimos 30 dias ficou de fora.")
    );
}

#[test]
fn labels_nested_projects_by_subfolder() {
    let fx = git_fixture();
    let repo = project(&fx, "mono", 60);
    write_bytes(&repo.join("client-v2/node_modules/pkg/blob"), TWO_MIB);
    fs::write(repo.join("client-v2/yarn.lock"), "").unwrap();
    let output = scan(&fx).unwrap();
    let labels: Vec<&str> = output.findings.iter().map(|f| f.label.as_str()).collect();
    assert_eq!(labels, vec!["mono", "mono (client-v2)"]);
    assert!(
        output.findings[1]
            .note
            .as_deref()
            .unwrap()
            .contains("yarn install")
    );
}

