#[test]
fn picks_install_command_by_lockfile() {
    let dir = tempfile::tempdir().unwrap();
    let project_dir = dir.path();
    assert_eq!(install_command(project_dir), "npm install");
    fs::write(project_dir.join("package-lock.json"), "").unwrap();
    assert_eq!(install_command(project_dir), "npm ci");
    fs::write(project_dir.join("bun.lockb"), "").unwrap();
    assert_eq!(install_command(project_dir), "bun install");
    fs::write(project_dir.join("yarn.lock"), "").unwrap();
    assert_eq!(install_command(project_dir), "yarn install");
    fs::write(project_dir.join("pnpm-lock.yaml"), "").unwrap();
    assert_eq!(install_command(project_dir), "pnpm install");
    let bun_text = tempfile::tempdir().unwrap();
    fs::write(bun_text.path().join("bun.lock"), "").unwrap();
    assert_eq!(install_command(bun_text.path()), "bun install");
}

