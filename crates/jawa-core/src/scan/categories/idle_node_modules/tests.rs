#[test]
fn describe_age_words() {
    let days = |count: u64| describe_age(Duration::from_secs(count * DAY + 100));
    assert_eq!(days(0), "hoje");
    assert_eq!(days(1), "ontem");
    assert_eq!(days(2), "há 2 dias");
    assert_eq!(days(59), "há 59 dias");
    assert_eq!(days(60), "há 2 meses");
    assert_eq!(days(729), "há 24 meses");
    assert_eq!(days(730), "há 2 anos");
    assert_eq!(days(1200), "há 3 anos");
}
