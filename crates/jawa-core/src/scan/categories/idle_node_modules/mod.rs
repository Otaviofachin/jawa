mod texts;

use std::fs;
use std::path::{Path, PathBuf};
use std::time::Duration;

use super::{Category, Descriptor, ScanOutput, ScanProblem};
use crate::model::finding::{CategoryId, Finding, Reversibility, Risk};
use crate::scan::paths::{PathItem, collect_findings};
use crate::scan::projects::find_named_dirs;
use crate::scan::projects::{all_repositories, git_for, repo_label, require_roots};
use crate::scan::{ScanContext, join_footnotes};
use crate::system::git::Git;
use crate::system::processes::holders_of;
use crate::system::runner::RunError;

const MAX_DEPTH: usize = 3;
const SECONDS_PER_DAY: u64 = 86_400;
const DAYS_PER_MONTH: u64 = 30;
const DAYS_PER_YEAR: u64 = 365;
const FIRST_MONTHS_DAY: u64 = 60;
const FIRST_YEARS_DAY: u64 = 730;

static DESCRIPTOR: Descriptor = Descriptor {
    id: CategoryId::IdleNodeModules,
    title: texts::TITLE,
    summary: texts::SUMMARY,
    explanation: texts::EXPLANATION,
};

pub struct IdleNodeModules;

struct IdleModules {
    repo: PathBuf,
    path: PathBuf,
    age: Duration,
}

impl Category for IdleNodeModules {
    fn descriptor(&self) -> &'static Descriptor {
        &DESCRIPTOR
    }

    fn roots(&self, ctx: &ScanContext) -> Vec<PathBuf> {
        ctx.project_roots.clone()
    }

    fn in_use_scope(&self, finding: &Finding) -> Option<PathBuf> {
        finding
            .action
            .path()
            .and_then(Path::parent)
            .map(Path::to_path_buf)
    }

    fn scan(&self, ctx: &ScanContext) -> Result<ScanOutput, ScanProblem> {
        let git = git_for(ctx)?;
        require_roots(ctx)?;
        let found = classify_repositories(&git, ctx);
        let items = found
            .idle
            .iter()
            .map(|entry| modules_item(&entry.repo, &entry.path, entry.age));
        let mut output = collect_findings(ctx, self, items)?;
        output.footnote = join_footnotes([
            output.footnote.take(),
            active_note(found.active_projects, ctx.config.idle_days),
            (found.failed_repos > 0).then(|| {
                format!(
                    "{} repositório(s) não puderam ser consultados pelo git.",
                    found.failed_repos
                )
            }),
        ]);
        Ok(output)
    }
}

#[derive(Default)]
struct RepositoryScan {
    idle: Vec<IdleModules>,
    active_projects: usize,
    failed_repos: usize,
}

fn classify_repositories(git: &Git, ctx: &ScanContext) -> RepositoryScan {
    let mut found = RepositoryScan::default();
    for repo in all_repositories(ctx) {
        let modules = match ignored_modules(git, &repo) {
            Ok(modules) => modules,
            Err(error) => {
                tracing::warn!(?repo, %error, "o git não respondeu para o repositório");
                found.failed_repos += 1;
                continue;
            }
        };
        if modules.is_empty() {
            continue;
        }
        match idle_age(git, ctx, &repo) {
            Some(age) => found
                .idle
                .extend(modules.into_iter().map(|path| IdleModules {
                    repo: repo.clone(),
                    path,
                    age,
                })),
            None => found.active_projects += 1,
        }
    }
    found
}

fn active_note(active_projects: usize, idle_days: u32) -> Option<String> {
    match active_projects {
        0 => None,
        1 => Some(format!(
            "1 projeto com atividade nos últimos {idle_days} dias ficou de fora."
        )),
        count => Some(format!(
            "{count} projetos com atividade nos últimos {idle_days} dias ficaram de fora."
        )),
    }
}

fn ignored_modules(git: &Git, repo: &Path) -> Result<Vec<PathBuf>, RunError> {
    let found = find_named_dirs(repo, &["node_modules"], MAX_DEPTH);
    let ignored = git.ignored_among(repo, &found)?;
    Ok(found
        .into_iter()
        .filter(|path| ignored.contains(path))
        .collect())
}

fn idle_age(git: &Git, ctx: &ScanContext, repo: &Path) -> Option<Duration> {
    let activity = git.last_activity(repo)?;
    let age = ctx.env.now.duration_since(activity).unwrap_or_default();
    let limit = Duration::from_secs(u64::from(ctx.config.idle_days) * SECONDS_PER_DAY);
    let has_process_inside = !holders_of(repo, &ctx.env.proc_root).is_empty();
    (age > limit && !has_process_inside).then_some(age)
}

fn modules_item<'a>(repo: &Path, path: &'a Path, age: Duration) -> PathItem<'a> {
    let project = path.parent().unwrap_or(path);
    let mut note = format!(
        "Última atividade {}. Para voltar: {}.",
        describe_age(age),
        install_command(project)
    );
    if let Some(registry) = private_registry(project, repo) {
        note.push_str(&format!(
            " Usa registry privado ({registry}): precisa de token válido no ~/.npmrc para reinstalar."
        ));
    }
    PathItem {
        category: CategoryId::IdleNodeModules,
        path,
        label: repo_label(repo, project),
        risk: Risk::Review,
        reversibility: Reversibility::Regenerable,
        note: Some(note),
        trash: false,
    }
}

fn install_command(project: &Path) -> &'static str {
    let has = |name: &str| project.join(name).exists();
    if has("pnpm-lock.yaml") {
        "pnpm install"
    } else if has("yarn.lock") {
        "yarn install"
    } else if has("bun.lock") || has("bun.lockb") {
        "bun install"
    } else if has("package-lock.json") {
        "npm ci"
    } else {
        "npm install"
    }
}

const GITHUB_PACKAGES_HOST: &str = "npm.pkg.github.com";
const GITHUB_PACKAGES: &str = "GitHub Packages";

fn private_registry(project: &Path, repo: &Path) -> Option<String> {
    let lines: Vec<String> = [project, repo]
        .iter()
        .filter_map(|dir| fs::read_to_string(dir.join(".npmrc")).ok())
        .flat_map(|text| {
            text.lines()
                .map(|line| line.trim().to_string())
                .collect::<Vec<_>>()
        })
        .filter(|line| !line.starts_with('#') && !line.starts_with(';'))
        .collect();
    lines
        .iter()
        .find_map(|line| scoped_registry(line))
        .or_else(|| lines.iter().find_map(|line| token_registry(line)))
}

fn scoped_registry(line: &str) -> Option<String> {
    let (scope, url) = line.split_once(":registry=")?;
    if !scope.starts_with('@') {
        return None;
    }
    let registry = registry_name(url_host(url));
    let preposition = if registry == GITHUB_PACKAGES {
        "no"
    } else {
        "em"
    };
    Some(format!("{scope} {preposition} {registry}"))
}

fn token_registry(line: &str) -> Option<String> {
    let (target, _) = line.split_once(":_authToken")?;
    Some(registry_name(url_host(target)))
}

fn url_host(url: &str) -> &str {
    let without_scheme = url.split_once("//").map_or(url, |(_, rest)| rest);
    without_scheme.split('/').next().unwrap_or(without_scheme)
}

fn registry_name(host: &str) -> String {
    if host == GITHUB_PACKAGES_HOST {
        GITHUB_PACKAGES.to_string()
    } else {
        host.to_string()
    }
}

fn describe_age(age: Duration) -> String {
    let days = age.as_secs() / SECONDS_PER_DAY;
    match days {
        0 => "hoje".to_string(),
        1 => "ontem".to_string(),
        2..FIRST_MONTHS_DAY => format!("há {days} dias"),
        FIRST_MONTHS_DAY..FIRST_YEARS_DAY => format!("há {} meses", days / DAYS_PER_MONTH),
        _ => format!("há {} anos", days / DAYS_PER_YEAR),
    }
}

